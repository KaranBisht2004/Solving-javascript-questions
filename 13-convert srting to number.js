// How to convert a string to a number?

// 1- use Number

let a = '100'// this string 
console.log(typeof(a));//string
console.log(typeof(Number(a)));//number

let b = Number(a)
console.log(typeof(b));//number

// 2- use +

let c = '500';
console.log(typeof(c));//string

let d = +c
console.log(typeof(d));//number
 