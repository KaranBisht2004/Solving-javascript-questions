// What are data types in JavaScript?


// JavaScript has two main categories of data types:
//  Primitive and Non-Primitive (Reference) types.

// 1- Primitive Data Types include 
// - String 
// - Number
// - Boolean
// - Undefined
// - Null
// - BigInt
// - Symbol
//  They are immutable, stored directly in Stack memory

// 2- Non-Primitive (Reference) Data Types include 
// - Objects
// - Arrays 
// - Functions
//  They are mutable, stored in Heap memory, 
// they share the same memory location pointer