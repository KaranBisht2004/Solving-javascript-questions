// What are template literals?

//Template literals are an ES6 string feature wrapped in backticks (`). and embed variables using ${}"


let name = "Karan";
let role = "Developer";

// Traditional way
console.log("Hi, I am " + name + " and I am a " + role + ".");

// Template Literal way
console.log(`Hi, I am ${name} and I am a ${role}.`);